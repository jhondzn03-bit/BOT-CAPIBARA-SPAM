const SCALE = 2;
const CHAR_W = 6 * SCALE;
const LINE_H = 9 * SCALE;
const PAD = 20;

function normalize(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase();
}

function putPixel(buf: Uint8Array, width: number, x: number, y: number, color: readonly number[]): void {
  if (x < 0 || y < 0 || x >= width) return;
  const i = (y * width + x) * 4;
  buf[i] = color[0];
  buf[i + 1] = color[1];
  buf[i + 2] = color[2];
  buf[i + 3] = 255;
}

function crc32(buf: Uint8Array): number {
  let crc = 0xffffffff;
  for (const byte of buf) {
    crc ^= byte;
    for (let i = 0; i < 8; i++) crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1;
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Uint8Array): Buffer {
  const out = Buffer.alloc(12 + data.length);
  out.writeUInt32BE(data.length, 0);
  out.write(type, 4, 'ascii');
  Buffer.from(data).copy(out, 8);
  out.writeUInt32BE(crc32(Buffer.concat([Buffer.from(type, 'ascii'), Buffer.from(data)])), 8 + data.length);
  return out;
}

/** Texto -> PNG. `highlights` son índices de líneas en color dorado. */
export function buildProofImage(title: string, lines: string[], highlights: number[] = []): Buffer {
  const all = [title, ...lines].map(normalize);
  const maxLen = all.reduce((max, line) => Math.max(max, line.length), 0);
  const width = Math.min(maxLen * CHAR_W + PAD * 2, 1400);
  const height = all.length * LINE_H + PAD * 2;
  const pixels = new Uint8Array(width * height * 4);

  const bg = [62, 39, 35];
  const cream = [255, 248, 220];
  const gold = [214, 168, 92];
  for (let i = 0; i < pixels.length; i += 4) {
    pixels[i] = bg[0];
    pixels[i + 1] = bg[1];
    pixels[i + 2] = bg[2];
    pixels[i + 3] = 255;
  }

  all.forEach((line, row) => {
    const color = row === 0 || highlights.includes(row - 1) ? gold : cream;
    let cursor = PAD;
    const y0 = PAD + row * LINE_H;
    for (const char of line) {
      const glyph = FONT[char] ?? FONT['?'];
      for (let gy = 0; gy < 7; gy++) {
        const bits = glyph[gy];
        for (let gx = 0; gx < 5; gx++) {
          if (bits & (1 << (4 - gx))) {
            for (let sy = 0; sy < SCALE; sy++) {
              for (let sx = 0; sx < SCALE; sx++) {
                putPixel(pixels, width, cursor + gx * SCALE + sx, y0 + gy * SCALE + sy, color);
              }
            }
          }
        }
      }
      cursor += CHAR_W;
    }
  });

  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (width * 4 + 1)] = 0;
    Buffer.from(pixels.buffer, y * width * 4, width * 4).copy(raw, y * (width * 4 + 1) + 1);
  }

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  const png = Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw)),
    chunk('IEND', new Uint8Array(0)),
  ]);
  return png;
}
